package db.migration;

import db.migration.V202611241455__renumber_unit_ids.UnitRow;
import org.flywaydb.core.api.migration.Context;
import org.junit.jupiter.api.Test;

import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static db.migration.V202611241455__renumber_unit_ids.alreadyRenumbered;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class RenumberUnitIdsMigrationTest {
    private static final List<String> OLD_ORDER = List.of(
            "Acid Angel from Asia", "+(KR)ystal Eyes", "LOVElution", "EVOLution", "Aria", "NXT", "Glow",
            "Visionary Vision", "msnz", "msnz moon", "msnz sun", "msnz neptune", "msnz zenith", "Acid Eyes",
            "∞!", "Alphie", "Aura"
    );
    private static final List<String> NEW_ORDER = List.of(
            "Acid Angel from Asia", "+(KR)ystal Eyes", "Acid Eyes", "LOVElution", "EVOLution", "NXT", "Aria",
            "Glow", "Visionary Vision", "∞!", "Alphie", "msnz", "msnz moon", "msnz sun", "msnz neptune",
            "msnz zenith", "Aura"
    );

    @Test
    void skipsEmptyUnitTableAndPreservesTheNextId() throws SQLException {
        try (var connection = DriverManager.getConnection("jdbc:h2:mem:");
             var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE unit (
                        unit_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 40) PRIMARY KEY,
                        unit_name VARCHAR(100), parent_unit_id BIGINT, visible BOOLEAN
                    )
                    """);
            Context context = mock(Context.class);
            when(context.getConnection()).thenReturn(connection);

            new V202611241455__renumber_unit_ids().migrate(context);

            statement.executeUpdate("INSERT INTO unit (unit_name) VALUES ('First unit')");
            try (var rows = statement.executeQuery("SELECT unit_id FROM unit")) {
                assertThat(rows.next()).isTrue();
                assertThat(rows.getLong("unit_id")).isEqualTo(40);
                assertThat(rows.next()).isFalse();
            }
        }
    }

    @Test
    void acceptsOriginalNumberingAndHistoricSeedNames() throws SQLException {
        var units = units(OLD_ORDER, 9);
        assertThat(alreadyRenumbered(units)).isFalse();
        units.put(1, new UnitRow("ACID ANGEL OF ASIA", null, true));
        units.put(10, new UnitRow("msnz Moon", 9, true));
        assertThat(alreadyRenumbered(units)).isFalse();
    }

    @Test
    void recognizesCompletedNumbering() throws SQLException {
        assertThat(alreadyRenumbered(units(NEW_ORDER, 12))).isTrue();
    }

    @Test
    void rejectsAnIncorrectNameWithTheCorrectRowCount() {
        var units = units(OLD_ORDER, 9);
        units.put(14, new UnitRow("LOVElution", null, true));
        assertThatThrownBy(() -> alreadyRenumbered(units)).isInstanceOf(SQLException.class);
    }

    @Test
    void rejectsAnUnexpectedRowCount() {
        var units = units(OLD_ORDER, 9);
        units.put(18, new UnitRow("Extra", null, true));
        assertThatThrownBy(() -> alreadyRenumbered(units)).isInstanceOf(SQLException.class)
                .hasMessageContaining("found 18");
    }

    @Test
    void rejectsNewIdsWithAnOldParentReference() {
        var units = units(NEW_ORDER, 12);
        units.put(13, new UnitRow("msnz moon", 9, true));
        assertThatThrownBy(() -> alreadyRenumbered(units)).isInstanceOf(SQLException.class);
    }

    @Test
    void rejectsAVisibleMsnzParent() {
        var units = units(OLD_ORDER, 9);
        units.put(9, new UnitRow("msnz", null, true));
        assertThatThrownBy(() -> alreadyRenumbered(units)).isInstanceOf(SQLException.class);
    }

    private static Map<Integer, UnitRow> units(List<String> names, int parentId) {
        Map<Integer, UnitRow> units = new HashMap<>();
        for (int id = 1; id <= names.size(); id++) {
            Integer parent = id > parentId && id <= parentId + 4 ? parentId : null;
            units.put(id, new UnitRow(names.get(id - 1), parent, id != parentId));
        }
        return units;
    }
}
